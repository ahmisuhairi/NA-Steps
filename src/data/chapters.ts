export function entryBelongsToChapter(
  entry: DictionaryEntry,
  chapter: ChapterDefinition,
): boolean {
  const inPdfRange = entry.pdfPages.some(
    (p) => p >= chapter.startPdfPage && p <= chapter.endPdfPage,
  );
  if (inPdfRange) return true;

  const excerptInRange = entry.excerpts.some(
    (ex) =>
      (ex.pdfPage >= chapter.startPdfPage && ex.pdfPage <= chapter.endPdfPage) ||
      ex.section.toLowerCase() === chapter.id.toLowerCase(),
  );
  if (excerptInRange) return true;

  const escaped = chapter.id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`\\b${escaped}\\b`, 'i').test(entry.section);
}
